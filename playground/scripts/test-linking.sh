#!/usr/bin/env bash
set -euo pipefail
repo="$(cd "$(dirname "$0")/../.." && pwd)"
out="$repo/build/linking"
compiler="${TOWER_NATIVE_BUILD:-$HOME/.cache/tower/native}/towerc"
sdk="${WASI_SDK_PATH:-$HOME/.cache/tower/wasi-sdk/wasi-sdk-34.0-x86_64-linux}"
mkdir -p "$out"
"$compiler" "$repo/scaffolding/tests/foreign-fixture.tower" --library -o "$out/native-fixture.o"
llvm-ar-19 rcs "$out/native-fixture.a" "$out/native-fixture.o"
"$compiler" "$repo/scaffolding/tests/foreign-fixture.tower" --library --target wasm32-unknown-unknown -o "$out/wasm-fixture.o"
"$sdk/bin/llvm-ar" rcs "$out/wasm-fixture.a" "$out/wasm-fixture.o"
"$compiler" "$repo/scaffolding/tests/linking.tower" --link "$out/native-fixture.a" -o "$out/native-linking" --raw-ir "$out/native.raw.ll" --optimized-ir "$out/native.optimized.ll"
"$out/native-linking" > "$out/native.txt"
printf '33\ntrue\ntrue\n42\n42\n18446744073709551615\n0\ntrue\n5\n42\n' > "$out/expected.txt"
diff -u "$out/expected.txt" "$out/native.txt"
"$compiler" "$repo/scaffolding/tests/linking.tower" --target wasm32-unknown-unknown --linker "$sdk/bin/wasm-ld" --link "$out/wasm-fixture.a" -o "$out/native-compiled.wasm"
"$compiler" "$repo/scaffolding/tests/linking.tower" --emit object -o "$out/tower.o"
clang "$out/tower.o" "$out/native-fixture.a" "$(dirname "$compiler")/share/tower/runtime-host-linux-x64.ll" -o "$out/separate-link"
"$out/separate-link" > "$out/separate.txt"
diff -u "$out/expected.txt" "$out/separate.txt"
"$compiler" "$repo/scaffolding/examples/memory.tower" -o "$out/native-memory"
"$out/native-memory" > "$out/memory.txt"
"$compiler" "$repo/scaffolding/examples/memory.tower" --interpret > "$out/interpreter.txt"
diff -u "$out/memory.txt" "$out/interpreter.txt"
printf '5\n84\n42\n' > "$out/memory-expected.txt"
diff -u "$out/memory-expected.txt" "$out/memory.txt"
printf 'Native executable, separate object/archive link, memory example and native-to-Wasm compilation passed.\n'

"$compiler" "$repo/scaffolding/tests/storage.tower" -o "$out/native-storage"
"$out/native-storage" > "$out/storage.txt"
"$compiler" "$repo/scaffolding/tests/storage.tower" --interpret > "$out/storage-interpreter.txt"
diff -u "$out/storage.txt" "$out/storage-interpreter.txt"
printf 'true\ntrue\n10\n84\ntrue\n0\ntrue\n16\ntrue\ntrue\n42\n200\ntrue\n597\n42\nfalse\n200\n' > "$out/storage-expected.txt"
diff -u "$out/storage-expected.txt" "$out/storage.txt"
"$compiler" "$repo/scaffolding/library/storage.tower" --library -o "$out/storage.o"
"$compiler" "$repo/scaffolding/library/bytes.tower" --library -o "$out/bytes.o"
printf 'Tower byte buffer/string builder, arena and growing map passed through interpretation, native execution and library-object emission.\n'
llvm_lib="$(${LLVM_CONFIG:-llvm-config-19} --libdir)/libLLVM.so"
"$compiler" "$repo/scaffolding/tests/llvm-c.tower" --link "$llvm_lib" -o "$out/llvm-c-api"
"$out/llvm-c-api" > "$out/llvm-c-api.txt"
printf '42\n' > "$out/llvm-c-expected.txt"
diff -u "$out/llvm-c-expected.txt" "$out/llvm-c-api.txt"
printf 'Tower linked to the real LLVM library and called its C API with raw opaque pointers.\n'

"$compiler" "$repo/scaffolding/tests/platform.tower" -o "$out/platform"
"$out/platform" > "$out/platform-native.txt"
"$compiler" "$repo/scaffolding/tests/platform.tower" --interpret > "$out/platform-interpreter.txt"
printf 'hello from Tower\n17\n-1\n' > "$out/platform-expected.txt"
diff -u "$out/platform-expected.txt" "$out/platform-native.txt"
diff -u "$out/platform-native.txt" "$out/platform-interpreter.txt"
printf 'Shared platform_write ABI passed in native code and the native interpreter.\n'
"$compiler" "$repo/scaffolding/tests/forward.tower" -o "$out/module-forward"
"$out/module-forward" > "$out/module-forward.txt"
printf '42\n' > "$out/module-forward-expected.txt"
diff -u "$out/module-forward-expected.txt" "$out/module-forward.txt"
printf 'Forward module functions, types and variables passed in a native executable.\n'
