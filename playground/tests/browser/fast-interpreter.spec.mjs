import {test,expect} from '@playwright/test';
import {selectDocument} from './project-helpers.mjs';
import {readFile} from 'node:fs/promises';
import {outputText} from './output-text.mjs';
test('three default runners compare and either interpreter can run independently',async({page})=>{
  await page.goto('/');await selectDocument(page,'functions.tower');
  await expect(page.locator('#execution-status')).toContainText('backends match');
  for(const id of ['execution-output','fast-output','llvm-output'])await expect(page.locator('#'+id)).toHaveText('720\n721\n');
  await expect.poll(()=>outputText(page,'fast-disassembly')).toContain('fn factorial');
  const download=page.waitForEvent('download');await page.locator('#fast-download').click();
  const artifact=await download, bytes=await readFile(await artifact.path());
  expect(artifact.suggestedFilename()).toMatch(/\.towerbc$/);
  expect(bytes.subarray(0,7).toString()).toBe('TOWERBC');expect(bytes.readUInt32LE(8)).toBe(1);
  await page.locator('#build-targets summary').click();
  await expect(page.locator('#target-interpreter')).toBeChecked();
  await expect(page.locator('#target-fast')).toBeChecked();
  await page.locator('#target-interpreter').uncheck();
  await page.locator('#target-wasm').uncheck();
  await page.locator('#build-targets summary').click();
  await expect(page.locator('#execution-status')).toHaveText('Finished');
  await expect(page.locator('#interpreter-column')).toBeHidden();
  await expect(page.locator('#wasm-column')).toBeHidden();
  await expect(page.locator('#fast-column')).toBeVisible();
  await expect(page.locator('#fast-output')).toHaveText('720\n721\n');
  await page.locator('#build-targets summary').click();
  await page.locator('#target-fast').uncheck();
  await page.locator('#target-interpreter').check();
  await page.locator('#build-targets summary').click();
  await expect(page.locator('#execution-status')).toHaveText('Finished');
  await expect(page.locator('#fast-column')).toBeHidden();
  await expect(page.locator('#execution-output')).toHaveText('720\n721\n');
});
